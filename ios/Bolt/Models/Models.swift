import Foundation

enum ChatRole: String, Codable, Equatable {
    case user
    case assistant
}

struct ChatMessage: Identifiable, Codable, Equatable {
    let id: String
    let role: ChatRole
    var content: String
}

struct ProjectFile: Identifiable, Codable, Equatable {
    var id: String { path }
    let path: String
    var content: String
    let language: String
}

struct ChatHistoryItem: Identifiable, Codable, Equatable {
    let id: String
    var description: String
    let createdAt: Date
    var messages: [ChatMessage]
    var files: [ProjectFile]
    var previewHtml: String
}

enum AppPane: String, CaseIterable, Equatable {
    case chat
    case code
    case preview
}

