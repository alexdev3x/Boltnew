          const todos = [
            { id: '1', text: 'Ship Bolt mobile', done: false },
            { id: '2', text: 'Polish the workbench', done: true },
          ];
          const list = document.getElementById('list');
          const input = document.getElementById('input');
          function render() {
            list.innerHTML = todos.map((t) =>
              '<div class="todo" data-id="' + t.id + '"><span class="' + (t.done ? 'done' : '') + '">' + t.text + '</span></div>'
            ).join('');
            [...list.children].forEach((el) => {
              el.onclick = () => {
                const todo = todos.find((t) => t.id === el.dataset.id);
                todo.done = !todo.done;
                render();
              };
            });
          }
          document.getElementById('add').onclick = () => {
            if (!input.value.trim()) return;
            todos.unshift({ id: String(Date.now()), text: input.value.trim(), done: false });
            input.value = '';
            render();
          };
          render();
        </script>
