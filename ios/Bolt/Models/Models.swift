                                    todos.insert(Todo(text: text, done: false), at: 0)
                                    text = ""
                                }
                                .buttonStyle(.borderedProminent)
                            }

                            List {
                                ForEach($todos) { $todo in
                                    Button {
                                        todo.done.toggle()
                                    } label: {
                                        Text(todo.text)
                                            .strikethrough(todo.done)
                                            .foregroundStyle(todo.done ? .secondary : .primary)
                                    }
                                }
                            }
                            .listStyle(.plain)
                        }
                        .padding()
                        .navigationTitle("Bolt Todos")
                    }
                }
            }
