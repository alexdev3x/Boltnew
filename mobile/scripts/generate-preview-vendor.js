#!/usr/bin/env node
/**
 * Bundles the browser-side runtime used by the in-app device preview
 * (React, ReactDOM, and Babel standalone) into self-contained JS strings
 * so the preview WebView never needs network access to a CDN.
 *
 * Run this whenever the `react` or `react-dom` dependency version changes:
 *   node scripts/generate-preview-vendor.js
 */
const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

const outDir = path.join(__dirname, '..', 'src', 'utils', 'vendor');
fs.mkdirSync(outDir, { recursive: true });

function writeVendorModule(name, code) {
  const filePath = path.join(outDir, `${name}.ts`);
  const banner = `// Auto-generated by scripts/generate-preview-vendor.js — do not edit by hand.\n`;
  fs.writeFileSync(filePath, `${banner}export default ${JSON.stringify(code)};\n`);
  console.log(`wrote ${filePath} (${(code.length / 1024).toFixed(0)} kB)`);
}

// React and ReactDOM must come out of a single esbuild bundle so they share
// the exact same 'react' module instance (and therefore the same hooks
// dispatcher) — bundling them separately silently duplicates 'react' and
// breaks hooks with "Cannot read properties of null (reading 'useState')".
async function bundleReactAndReactDom() {
  const entry = path.join(outDir, '.react-entry.tmp.js');
  fs.writeFileSync(
    entry,
    [
      "import React from 'react';",
      "import { createRoot } from 'react-dom/client';",
      'window.React = React;',
      'window.ReactDOM = { createRoot: createRoot };',
      '',
    ].join('\n'),
  );
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    define: { 'process.env.NODE_ENV': '"production"' },
    write: false,
  });
  fs.unlinkSync(entry);
  return result.outputFiles[0].text;
}

function readBabelStandalone() {
  const babelPath = require.resolve('@babel/standalone/babel.min.js');
  return fs.readFileSync(babelPath, 'utf8');
}

async function main() {
  const [reactBundle, babel] = await Promise.all([
    bundleReactAndReactDom(),
    Promise.resolve(readBabelStandalone()),
  ]);
  writeVendorModule('reactAndReactDom', reactBundle);
  writeVendorModule('babel', babel);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
